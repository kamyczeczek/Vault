"""Standalone preflight for this project.

Answer for a cold agent: can work start here, in this tree, right now?
Checks local hard dependencies, then sibling links this project's docs
point at. Siblings live under ``$WORKSPACE_ROOT`` (default: this
project's parent directory, i.e. ``projects/research/``). Missing optional
siblings degrade the project; missing hard files block it.

    python preflight.py              # report + exit code
    WORKSPACE_ROOT=... preflight.py  # point at a different siblings tree
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SIBLINGS = Path(os.environ.get("WORKSPACE_ROOT", ROOT.parent))

# (severity, path, why it matters). Only "hard" counts toward the exit code.
CHECKS: list[tuple[str, Path, str]] = [
    # Local — hard
    ("hard", ROOT / "CLAUDE.md", "entry file; cannot route without it"),
    ("hard", ROOT / "CONTEXT.md", "contract; model interface, evaluation protocol, leakage rules"),
    ("hard", ROOT / "bench.py", "S-47 suite; the project's core runner"),
    ("hard", ROOT / "members/big_dict_elm.py", "incumbent model that H720/R&D lines import"),
    ("hard", ROOT / "members/knn_feature_forecaster.py", "incumbent baseline"),
    # Local — optional (regenerated artifact)
    ("optional", ROOT / "results/results_s47.json",
     "committed evidence the project is ranked by; regenerated by bench.py, not a startup dependency"),
    # Sibling — hard for specific runners
    ("hard", SIBLINGS.parent / "_archive/datasets/fetch_scientific_datasets.py",
     "imported by benchmark_multi_horizon.py, heuristic_hyperparameter_search.py, scripts/diebold_mariano_test.py"),
    ("hard", SIBLINGS.parent / "_archive/datasets/data",
     "fetched datasets for the multi-domain runners"),
    # Sibling — advisory
    ("optional", SIBLINGS / "etth1-h720",
     "downstream consumer of this project (no code dependency on it from here)"),
]


def _shown(path: Path) -> str:
    for base in (ROOT, SIBLINGS, SIBLINGS.parent):
        if path.is_relative_to(base):
            return str(path.relative_to(base))
    return str(path)


def main() -> int:
    missing = 0
    for severity, path, why in CHECKS:
        ok = path.exists()
        base = "local" if path.is_relative_to(ROOT) else "ext  "
        print(f"  [{'ok' if ok else 'MISSING'}] {base} {_shown(path)}  ({why})")
        if not ok and severity == "hard":
            missing += 1
    verdict = "NOT READY" if missing else "READY"
    print(f"benchmark-core preflight: {verdict} ({missing} hard missing)")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())

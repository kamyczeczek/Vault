#!/usr/bin/env python3
"""
gen_digest.py — Generate the brain-local reflection routing digest.

Renders reflection_index.json into marker-delimited digest.md.
Newest scars first; token-budgeted, read explicitly by the agent.
No overlay or private-memory dependency.

Usage:
    python brain/gen_digest.py            # rebuild in place
    python brain/gen_digest.py --check    # exact bytes; no writes
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BRAIN = Path(__file__).resolve().parent
INDEX = BRAIN / "reflection_index.json"
DIGEST_FILE = BRAIN / "digest.md"

START = ("<!-- SCAR-BRAIN-DIGEST:BEGIN "
         "(auto-generated by brain/gen_digest.py — do not edit between markers) -->")
END = "<!-- SCAR-BRAIN-DIGEST:END -->"

DEFAULT_MAX_TOKENS = 900


def tok(s: str) -> int:
    cjk = sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")
    return len(s.replace("\n", " ").split()) + cjk


def short(desc: str, budget: int) -> str:
    desc = desc.replace("\n", " ").strip()
    if tok(desc) <= budget:
        return desc
    out, cur = "", 0
    for w in desc.split(" "):
        t = tok(w)
        if cur + t + 1 > budget:
            break
        out = f"{out} {w}".strip()
        cur += t
    return out.rstrip(",;: -") + "..."


def render(index: dict, max_tokens: int) -> str:
    scars = list(index["scars"])
    # Newest first, stable tie-break.
    scars.sort(key=lambda s: (s["stem"], s["id"]), reverse=True)
    fp = index["fingerprint"]
    lines = [
        "## Scar routing signals (reflection_brain — read-consulted, deterministic)",
        "",
        f"Source: `brains/reflection_brain/reflection_index.json` "
        f"({index['scar_count']} scars from {index['file_count']} reflections, "
        f"fingerprint `{fp}`). These are the workspace's accumulated scars — "
        "deterministic prevention invariants from solved problems. Rules:",
        "- Before acting on a surface a scar covers, treat its invariant as "
        "binding; the scar's Source line is the full evidence trail.",
        "- Read this local digest explicitly. Optional Mnemopi recall is a "
        "hint, never a replacement for the corpus or verified digest.",
        "- **Mid-session freshness:** this digest is a snapshot as of the "
        "last reflection commit. After any commit touching "
        "`MONITORING/reflection/`, probe: `python "
        "brains/reflection_brain/ask.py --check-stale` — if STALE, rebuild "
        "with the printed command.",
        "- Full scar text: `python brains/reflection_brain/ask.py \"query\"` "
        "or `ask.py list <slug-fragment>`.",
        "",
        "| Scar | Invariant (truncated) |",
        "|---|---|",
    ]
    overhead = sum(tok(f"| {s['stem'].split('_', 2)[2]} {s['id']} | ")
                   for s in scars) + 10
    per = max(16, (max_tokens - overhead) // max(1, len(scars)))
    for s in scars:
        session = s["stem"].split("_", 2)[2]
        lines.append(f"| {session} {s['id']} | {short(s['invariant'], per)} |")
    lines.append("")
    lines.append(
        f"{index['scar_count']} scars total, newest first; older scars remain "
        "queryable via `ask.py list`." if len(scars) else "No scars yet.")
    return "\n".join(lines)


def markers_text(index: dict, max_tokens: int) -> str:
    return f"{START}\n{render(index, max_tokens)}\n{END}"




def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--max-tokens", type=int, default=DEFAULT_MAX_TOKENS)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if local digest bytes differ from a fresh render")
    args = ap.parse_args(argv)

    if not INDEX.exists():
        print("FAIL: reflection_index.json missing — run "
              "build_reflection_index.py first", file=sys.stderr)
        return 2
    index = json.loads(INDEX.read_text(encoding="utf-8"))
    digest = (markers_text(index, args.max_tokens) + "\n").encode("utf-8")
    if args.check:
        if not DIGEST_FILE.exists():
            print("[scar gen_digest] local digest missing", file=sys.stderr)
            return 1
        if DIGEST_FILE.read_bytes() != digest:
            print("[scar gen_digest] STALE: local digest differs from fresh render",
                  file=sys.stderr)
            return 1
        print("[scar gen_digest] local digest in sync")
        return 0
    DIGEST_FILE.write_bytes(digest)
    print(f"[scar gen_digest] local digest updated "
          f"({tok(render(index, args.max_tokens))} tokens est.)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

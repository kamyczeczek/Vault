#!/usr/bin/env python3
"""
sync_brain.py — Automatic synchronizer between projects/ts-ml-experiments/h720
and ROOT/brains/ts_brain/.

Scans CONTEXT.md, data.py, methods/, and sub_experiments/ in h720, updates
the corpus in brains/ts_brain/corpus/, regenerates the auto-injected
"Top Leaderboard" line in both ts-brain.ts extension copies, and triggers
build_graph.py.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

TS_ROOT = Path(__file__).resolve().parent
H720_DIR = TS_ROOT / "h720"
ROOT_DIR = TS_ROOT.parent.parent
BRAIN_DIR = ROOT_DIR / "brains" / "ts_brain"
CORPUS_DIR = BRAIN_DIR / "corpus"

EXTENSION_PATHS = [
    ROOT_DIR / "workspaces" / "ts-brain" / ".omp" / "extensions" / "ts-brain.ts",
]

MARKER_RE = re.compile(
    r"(// LEADERBOARD_START \(auto-generated by sync_brain\.py — do not edit\)\r?\n)"
    r"(.*?)"
    r"(\r?\n\s*// LEADERBOARD_END)",
    re.DOTALL,
)


def sync_from_h720_context() -> str:
    """Extract leaderboard + subexperiment sections from h720/CONTEXT.md into
    corpus chunk 04. Returns the raw leaderboard table content ('' if
    CONTEXT.md is missing)."""
    context_file = H720_DIR / "CONTEXT.md"
    if not context_file.exists():
        print(f"Warning: {context_file} not found.")
        return ""

    text = context_file.read_text(encoding="utf-8", errors="replace")

    # 1. Extract Leaderboard
    lb_match = re.search(r"<!-- LEADERBOARD_START -->(.*?)<!-- LEADERBOARD_END -->", text, re.DOTALL)
    leaderboard_content = lb_match.group(1).strip() if lb_match else ""

    # 2. Extract Subexperiment sections
    subexp_matches = re.findall(r"(## Sub-Experiment:.*?)(?=(?:## Sub-Experiment:|\Z))", text, re.DOTALL)
    subexp_content = "\n\n".join(s.strip() for s in subexp_matches)

    # Write updated leaderboard & findings chunk
    lb_chunk = CORPUS_DIR / "04_subexperiment_findings_leaderboard.md"
    lb_chunk.write_text(f"""---
id: 04_subexperiment_findings_leaderboard
title: "Sub-Experiment Leaderboards & Empirical Findings"
source: "projects/ts-ml-experiments/h720/CONTEXT.md"
tags: [leaderboard, findings, results, elm, knn, temporal_knn]
---

# Sub-Experiment Leaderboard & Key Empirical Findings

## Official H=720 Leaderboard
{leaderboard_content}

## Sub-Experiment Summaries & Findings
{subexp_content}
""", encoding="utf-8")
    print(f"Updated {lb_chunk}")
    return leaderboard_content


def top_leaderboard_line(leaderboard_content: str) -> str:
    """Build the injected '- Top Leaderboard:' line: top-3 distinct model
    families by best (lowest) MAE, from the CONTEXT.md leaderboard table."""
    best: dict[str, tuple[str, float]] = {}
    for row in leaderboard_content.splitlines():
        row = row.strip()
        if not row.startswith("|") or "MAE" in row or "---" in row:
            continue
        cells = [c.strip().strip("*") for c in row.strip("|").split("|")]
        if len(cells) < 2 or not cells[1]:
            continue
        try:
            mae = float(cells[1])
        except ValueError:
            continue
        family = cells[0].split(" (")[0].strip()
        if not family:
            continue
        if family not in best or mae < best[family][1]:
            best[family] = (cells[0], mae)
    top = sorted(best.values(), key=lambda v: v[1])[:3]
    if len(top) < 3:
        raise ValueError(
            f"leaderboard parse failed: expected 3 distinct families, got {top!r}"
        )
    return (f"- Top Leaderboard: {top[0][0]} (MAE {top[0][1]:.4f}), "
            f"{top[1][0]} (MAE {top[1][1]:.4f}), "
            f"{top[2][0]} (MAE {top[2][1]:.4f}).")


def sync_extension_leaderboard(leaderboard_content: str) -> None:
    """Regenerate the marked leaderboard region in both ts-brain.ts copies so
    the auto-injected context can never go stale when results change."""
    line = top_leaderboard_line(leaderboard_content)
    escaped = line.replace("\\", "\\\\").replace('"', '\\"')
    push = f'    lines.push("{escaped}");'
    for ext_path in EXTENSION_PATHS:
        if not ext_path.exists():
            raise FileNotFoundError(f"extension copy missing: {ext_path}")
        text = ext_path.read_text(encoding="utf-8")
        if not MARKER_RE.search(text):
            raise ValueError(f"LEADERBOARD markers missing in {ext_path}")
        updated = MARKER_RE.sub(lambda m: m.group(1) + push + m.group(3), text, count=1)
        if updated != text:
            ext_path.write_text(updated, encoding="utf-8")
            print(f"Updated {ext_path}")
        else:
            print(f"Unchanged {ext_path} (already current)")


def main() -> int:
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    print("Syncing time series knowledge from h720 project into ts_brain...")
    leaderboard_content = sync_from_h720_context()
    if leaderboard_content:
        sync_extension_leaderboard(leaderboard_content)
    else:
        print("Warning: empty leaderboard — extension injection line left unchanged.")

    # Rebuild graph
    build_graph_py = ROOT_DIR / "build_graph.py"
    if build_graph_py.exists():
        subprocess.run([sys.executable, str(build_graph_py), "--brain", "ts_brain"], check=True)

    # Verify sync
    verify_py = BRAIN_DIR / "verify_sync.py"
    if verify_py.exists():
        subprocess.run([sys.executable, str(verify_py)], check=True)

    print("Sync complete.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

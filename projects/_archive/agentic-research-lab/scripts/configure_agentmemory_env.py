#!/usr/bin/env python3
"""Generate ~/.agentmemory/.env so agentmemory distillation works for good.

Root-cause fix, not a per-session patch:
  * agentmemory runs "zero-LLM" out of the box -> episodic/semantic tiers,
    knowledge-graph extraction and LLM summarization are all no-ops.
  * snapshots / consolidation / slots are opt-in and default off.

This script reads the machine's OpenAI-compatible LLM router (default: the
"nara" provider from pi's models.json) and writes a ~/.agentmemory/.env that:
  - sets OPENAI_API_KEY / OPENAI_BASE_URL / OPENAI_MODEL so the LLM tiers work
  - enables SNAPSHOT_ENABLED, CONSOLIDATION_ENABLED, AGENTMEMORY_SLOTS,
    GRAPH_EXTRACTION_ENABLED

Safety:
  - stdlib only; no network; no secrets printed (values masked in output).
  - back up any existing .env to .env.<ts>.bak before writing.
  - idempotent: a non-empty key already present in .env is never clobbered.

After running, restart the agentmemory worker so it loads the new .env:
  agentmemory stop --force && agentmemory
(On this host the engine is native; `agentmemory stop` may need --force.)
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

MASK = lambda v: (v[:5] + "..." + str(len(v))) if len(v) > 5 else "(short)"


def _pi_models_path() -> Path:
    return Path(os.path.expanduser("~")) / ".pi" / "agent" / "models.json"


def read_router(provider_id: str) -> tuple[str, str]:
    """Return (api_key, base_url) for an OpenAI-compatible router from pi config."""
    data = json.loads(_pi_models_path().read_text(encoding="utf-8"))
    prov = data.get("providers", {}).get(provider_id)
    if not prov:
        raise SystemExit(f"provider '{provider_id}' not found in {_pi_models_path()}")
    key = prov.get("apiKey", "")
    base = prov.get("baseUrl", "").rstrip("/")
    if not base.endswith("/v1"):
        base += "/v1"
    if not key:
        raise SystemExit(f"provider '{provider_id}' has no apiKey")
    return key, base


def mask_env_content(content: str) -> str:
    """Print .env with secret-looking values masked."""
    out = []
    for line in content.splitlines():
        m = re.match(r"^([A-Z0-9_]+)=(.*)$", line)
        if m and ("KEY" in m.group(1) or "SECRET" in m.group(1)):
            out.append(f"{m.group(1)}={MASK(m.group(2))}")
        else:
            out.append(line)
    return "\n".join(out)


def validate_model(api_key: str, base: str, model: str) -> list[str]:
    """Return the router's model ids; raises if the endpoint is unreachable.

    Stdlib only (urllib). One lightweight GET per generation run.
    """
    import urllib.request

    req = urllib.request.Request(
        base + "/models",
        headers={"Authorization": f"Bearer {api_key}"},
    )
    with urllib.request.urlopen(req, timeout=15) as resp:
        data = json.load(resp)
    ids = [m["id"] for m in data.get("data", [])]
    if model not in ids:
        free = [i for i in ids if "free" in i]
        hint = free[0] if free else (ids[0] if ids else "?")
        raise SystemExit(
            f"model '{model}' is not served by {base} (configured OPENAI_MODEL would 404). "
            f"Pass a valid id as arg 2; candidates: {', '.join(free[:5])}"
        )
    return ids


def build_env(provider_id: str, model: str) -> str:
    key, base = read_router(provider_id)
    lines = [
        "# agentmemory persistent config -- generated by scripts/configure_agentmemory_env.py",
        "# Re-run the generator to refresh; existing non-empty keys are preserved on merge.",
        "# LLM source: OpenAI-compatible router from pi models.json",
        f"OPENAI_API_KEY={key}",
        f"OPENAI_BASE_URL={base}",
        f"OPENAI_MODEL={model}",
        "# Durable layers",
        "SNAPSHOT_ENABLED=true",
        "CONSOLIDATION_ENABLED=true",
        "AGENTMEMORY_SLOTS=true",
        "GRAPH_EXTRACTION_ENABLED=true",
        "# Consolidation floor (dist patch P2): unblock semantic at 1 episode summary",
        "AGENTMEMORY_SEMANTIC_MIN_SUMMARIES=1",
        "",
    ]
    return "\n".join(lines)


def merge_into_existing(existing: str, fresh: str) -> str:
    """Preserve non-empty values already set by the user in the old .env."""
    fresh_vars = dict(re.findall(r"^([A-Z0-9_]+)=(.*)$", fresh, re.M))
    kept = []
    fresh_keys = set(fresh_vars)
    for line in existing.splitlines():
        m = re.match(r"^([A-Z0-9_]+)=(.*)$", line)
        if m and m.group(1) in fresh_keys:
            if m.group(2).strip():
                # user already set a real value: keep it, don't clobber
                kept.append(line)
            # else: fall through to fresh value
        elif not line.startswith("#"):
            kept.append(line)
    # append any fresh vars not already kept
    kept_keys = set(re.findall(r"^([A-Z0-9_]+)=", "\n".join(kept), re.M))
    for k, v in fresh_vars.items():
        if k not in kept_keys:
            kept.append(f"{k}={v}")
    return "\n".join(kept) + "\n"


def main() -> None:
    provider = sys.argv[1] if len(sys.argv) > 1 else "nara"
    model = sys.argv[2] if len(sys.argv) > 2 else "nemotron-3.5-lightning-free"
    env_path = Path(os.path.expanduser("~")) / ".agentmemory" / ".env"
    env_path.parent.mkdir(parents=True, exist_ok=True)

    fresh = build_env(provider, model)
    try:
        validate_model(*read_router(provider), model)
    except SystemExit:
        raise
    except Exception as e:  # network failure: warn, don't block (offline runs)
        print(f"warning: could not validate model against router ({e}); proceeding")
    if env_path.exists():
        old = env_path.read_text(encoding="utf-8")
        ts = time.strftime("%Y%m%d-%H%M%S")
        shutil.copy2(env_path, env_path.with_name(f".env.{ts}.bak"))
        content = merge_into_existing(old, fresh)
        note = f"merged over existing .env (backup .env.{ts}.bak)"
    else:
        content = fresh
        note = "created new .env"

    env_path.write_text(content, encoding="utf-8")
    env_path.chmod(0o600)
    if os.name == "nt":
        # chmod is a no-op on NTFS; restrict the real ACL (scar 2026-09-30: .env was 0666)
        me = os.environ.get("USERNAME", "")
        r = subprocess.run(["icacls", str(env_path), "/inheritance:r", f"/grant:r", f"{me}:R,W"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(f"WARN: icacls ACL restriction failed (best-effort): {r.stderr.strip()}")
        else:
            print(f"  .env ACL restricted to {me} (inheritance removed)")
    print(f"agentmemory .env ({note}) at {env_path}")
    print("--- effective config (masked) ---")
    print(mask_env_content(content))
    print("--- next: restart the worker to load it ---")
    print("  agentmemory stop --force ; agentmemory")


if __name__ == "__main__":
    main()

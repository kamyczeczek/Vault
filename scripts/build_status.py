#!/usr/bin/env python3
"""Build handoff/status/STATUS.md from flags + decisions + NEXT.md.

ICM invariants this rests on:
  4  every folder-level contract is explicit -> handoff/status/CONTEXT.md
  9  the filesystem is the state machine; a generated index is never hand-edited

STATUS.md is the human-facing view of workspace state: gates snapshot, the
single next sentence, open owner decisions, stale flags, and the full flag
table. It is rebuilt from `handoff/flags/*.md` + `handoff/decisions/*.md` +
`handoff/status/NEXT.md`. Never hand-edit; `--check` detects drift.

Usage:
    python scripts/build_status.py                # -> handoff/status/STATUS.md
    python scripts/build_status.py --check        # exit 1 if the view is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FLAGS = ROOT / "handoff" / "flags"
DECISIONS = ROOT / "handoff" / "decisions"
STATUS_DIR = ROOT / "handoff" / "status"
NEXT_MD = STATUS_DIR / "NEXT.md"
STATE_MD = ROOT / "STATE.md"
DEFAULT_OUT = STATUS_DIR / "STATUS.md"

FLAG_KEYS = ("flag", "since", "owner", "agent", "model", "origin")
DECISION_KEYS = ("status", "recommendation", "decided_at", "owner")
FLAG_RX = {k: re.compile(rf"^{k}:\s*(.+?)\s*$") for k in FLAG_KEYS}
DEC_RX = {k: re.compile(rf"^{k}:\s*(.*)$") for k in DECISION_KEYS}

STALE_DAYS = 14
HEADER = "<!-- generated by scripts/build_status.py; do not edit -->"

def parse_flag(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    meta: dict[str, str] = {}
    i = 0
    if lines and lines[0].strip() == "---":
        i = 1
        while i < len(lines) and lines[i].strip() != "---":
            s = lines[i].strip()
            for k in FLAG_KEYS:
                m = FLAG_RX[k].match(s)
                if m:
                    meta[k] = m.group(1)
            i += 1
        i += 1 if i < len(lines) and lines[i].strip() == "---" else 0
    body = "\n".join(lines[i:]).strip()
    if meta.get("flag") and meta["flag"] != path.stem:
        meta["problem"] = f"flag `{meta['flag']}` != filename `{path.stem}`"
    meta.setdefault("flag", path.stem)
    meta["path"] = path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else path.name
    meta["body"] = body
    return meta

def parse_decision(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    meta: dict[str, str] = {}
    i = 0
    if lines and lines[0].strip() == "---":
        i = 1
        while i < len(lines) and lines[i].strip() != "---":
            s = lines[i].strip()
            for k in DECISION_KEYS:
                m = DEC_RX[k].match(s)
                if m:
                    meta[k] = m.group(1).strip()
            i += 1
        i += 1 if i < len(lines) and lines[i].strip() == "---" else 0
    body = "\n".join(lines[i:]).strip()
    meta.setdefault("status", "open")
    meta.setdefault("recommendation", "")
    meta.setdefault("decided_at", "")
    meta.setdefault("owner", "?")
    meta["slug"] = path.stem
    meta["path"] = path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else path.name
    meta["body"] = body
    return meta

def newest_since(flags: list[dict], fallback: date | None = None) -> date:
    since = [f["since"] for f in flags if f.get("since")]
    if since:
        try:
            return date.fromisoformat(max(since))
        except ValueError:
            pass
    return fallback or date.today()

def strip_frontmatter(text: str) -> str:
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        i = 1
        while i < len(lines) and lines[i].strip() != "---":
            i += 1
        i += 1 if i < len(lines) and lines[i].strip() == "---" else 0
        return "\n".join(lines[i:]).strip()
    return text.strip()

def collect(flags_dir: Path = FLAGS, decisions_dir: Path = DECISIONS,
            next_path: Path = NEXT_MD):
    flags: list[dict] = []
    problems: list[str] = []
    decisions: list[dict] = []
    if flags_dir.is_dir():
        for p in sorted(flags_dir.glob("*.md")):
            if p.name == "INDEX.md":
                continue
            f = parse_flag(p)
            flags.append(f)
            if "problem" in f:
                problems.append(f"{f['path']}: {f['problem']}")
            if not f.get("since"):
                problems.append(f"{f['path']}: missing `since`")
    flags.sort(key=lambda f: (f.get("since", ""), f["flag"]), reverse=True)

    if decisions_dir.is_dir():
        for p in sorted(decisions_dir.glob("*.md")):
            if p.name == "CONTEXT.md":
                continue
            decisions.append(parse_decision(p))

    next_text = next_path.read_text(encoding="utf-8") if next_path.is_file() else ""
    return flags, decisions, problems, next_text

def render(flags: list[dict], decisions: list[dict], next_text: str,
           problems: list[str] | None = None, stale_days: int = STALE_DAYS,
           as_of: date | str | None = None) -> str:
    if problems is None:
        problems = []
    if as_of is None:
        anchor = newest_since(flags)
    elif isinstance(as_of, str):
        anchor = date.fromisoformat(as_of)
    else:
        anchor = as_of
    cutoff = (anchor - timedelta(days=stale_days)).isoformat()
    stale_flags = [f for f in flags if f.get("since") and f["since"] < cutoff]

    out: list[str] = [HEADER, "", "# STATUS", ""]

    # Gates
    out += ["## Gates", ""]
    out.append("Machine snapshot: `STATE.md` (integrity gate + git state; "
               "rebuild with `python scripts/build_state.py`).")
    out.append("")

    # Next
    out += ["## Next", ""]
    next_body = strip_frontmatter(next_text) if next_text.strip() else "(missing NEXT.md)"
    out.append(next_body)
    out.append("")

    # Open decisions
    out += ["## Open decisions", ""]
    open_decisions = [d for d in decisions if str(d.get("status", "open")).lower() == "open"]
    if open_decisions:
        for d in open_decisions:
            rec = d.get("recommendation", "")
            owner = d.get("owner", "?")
            decided_at = d.get("decided_at", "") or "pending"
            out.append(f"- **`{d['slug']}`** — recommendation: {rec} "
                       f"(owner: {owner}, decided_at: {decided_at})")
    else:
        out.append("(none)")
    out.append("")

    # Stale
    out += ["## Stale", ""]
    if stale_flags:
        for f in stale_flags:
            out.append(f"- `{f['flag']}` — since {f.get('since', '?')} "
                       f"(older than {stale_days} days)")
    else:
        out.append("(none)")
    out.append("")

    # Flags
    out += ["## Flags", ""]
    out += ["| flag | since | owner | agent |",
            "| --- | --- | --- | --- |"]
    for f in flags:
        out.append(f"| `{f['flag']}` | {f.get('since', '?')} | {f.get('owner', '?')} "
                   f"| {f.get('agent', '?')} |")
    out.append("")

    return "\n".join(out).rstrip() + "\n"

def is_stale(out: Path, text: str) -> bool:
    return (not out.exists()) or out.read_text(encoding="utf-8") != text

def main() -> int:
    ap = argparse.ArgumentParser(prog="build_status.py")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if STATUS.md is missing or stale")
    ap.add_argument("--as-of", type=date.fromisoformat, default=None,
                    help="reference date for the stale window; default = newest flag `since`")
    ap.add_argument("-o", "--out", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args()

    flags, decisions, problems, next_text = collect()
    text = render(flags, decisions, next_text, problems, as_of=a.as_of)

    if a.check:
        if problems:
            for p in problems:
                print(f"PROBLEM {p}")
        rc = 0
        if is_stale(a.out, text):
            print(f"STALE {a.out} — run: python scripts/build_status.py")
            rc = 1
        else:
            print(f"OK {a.out.name}: {len(flags)} flags, {len([d for d in decisions if str(d.get('status','open')).lower()=='open'])} open decisions, view current")
        return 1 if problems else rc

    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {a.out}  ({len(flags)} flags, "
          f"{len([d for d in decisions if str(d.get('status','open')).lower()=='open'])} open decisions)")
    return 0

if __name__ == "__main__":
    sys.exit(main())

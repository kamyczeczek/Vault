#!/usr/bin/env python3
"""Hermetic tests for scripts/build_status.py."""
from __future__ import annotations

import sys
import tempfile
import unittest
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_status as bs  # noqa: E402


FLAG_A = """---
flag: alpha_done
since: 2026-10-18
owner: agent-a
agent: agent-a
model: opencode/some-model
---

`alpha_done` — 2026-10-18: shipped the thing. Next: nothing.
"""

FLAG_OLD = """---
flag: old_one
since: 2026-10-01
owner: agent-b
agent: agent-b
model: other/model
---

`old_one` — 2026-10-01: old. Next: nothing.
"""

DEC_OPEN = """---
status: open
recommendation: do the thing
decided_at:
owner: mateusz
---

body
"""

DEC_DECIDED = """---
status: decided
recommendation: done
decided_at: 2026-10-18
owner: mateusz
---

body
"""


class BuildStatusTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.flags = self.tmp / "flags"
        self.decisions = self.tmp / "decisions"
        self.status_dir = self.tmp / "status"
        self.flags.mkdir()
        self.decisions.mkdir()
        self.status_dir.mkdir()
        (self.flags / "alpha_done.md").write_text(FLAG_A, encoding="utf-8")
        (self.flags / "old_one.md").write_text(FLAG_OLD, encoding="utf-8")
        (self.decisions / "open_q.md").write_text(DEC_OPEN, encoding="utf-8")
        (self.decisions / "done_q.md").write_text(DEC_DECIDED, encoding="utf-8")
        self.next_path = self.status_dir / "NEXT.md"
        self.next_path.write_text("---\nverified_at: 2026-10-18\n---\n\nNEXT: do X.\n", encoding="utf-8")
    def collect(self):
        return bs.collect(self.flags, self.decisions, self.next_path)

    def test_render_is_deterministic(self):
        flags, decisions, problems, next_text = self.collect()
        r1 = bs.render(flags, decisions, next_text, problems, as_of="2026-10-18")
        r2 = bs.render(flags, decisions, next_text, problems, as_of="2026-10-18")
        self.assertEqual(r1, r2)

    def test_is_stale_detects_missing_and_changed(self):
        out = self.tmp / "STATUS.md"
        text = "x\n"
        self.assertTrue(bs.is_stale(out, text))
        out.write_text(text, encoding="utf-8")
        self.assertFalse(bs.is_stale(out, text))
        out.write_text("y\n", encoding="utf-8")
        self.assertTrue(bs.is_stale(out, text))

    def test_empty_flags_yields_header(self):
        empty = self.tmp / "empty_flags"
        empty.mkdir()
        flags, decisions, problems, next_text = bs.collect(
            empty, self.decisions, self.next_path)
        self.assertEqual(flags, [])
        text = bs.render(flags, decisions, next_text, problems, as_of="2026-10-18")
        self.assertIn("<!-- generated by scripts/build_status.py; do not edit -->", text)
        self.assertIn("# STATUS", text)
        self.assertIn("## Flags", text)

    def test_open_decisions_rendered_decided_excluded(self):
        flags, decisions, problems, next_text = self.collect()
        text = bs.render(flags, decisions, next_text, problems, as_of="2026-10-18")
        self.assertIn("open_q", text)
        self.assertNotIn("done_q", text)

    def test_stale_section_lists_old_flags(self):
        flags, decisions, problems, next_text = self.collect()
        text = bs.render(flags, decisions, next_text, problems, as_of="2026-10-18")
        self.assertIn("old_one", text)
        self.assertIn("## Stale", text)

    def test_newest_since_anchor(self):
        flags, *_ = self.collect()
        self.assertEqual(bs.newest_since(flags), date(2026, 10, 18))


if __name__ == "__main__":
    unittest.main(verbosity=2)

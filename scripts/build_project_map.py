#!/usr/bin/env python3
"""Build (or check) a project's MAP.md — one row per module (D9).

"Clear usage of each module" is a query, not a vibe: a reader needs to ask
"what does this file do, what does it take, what does it return, who calls it"
without opening 90 files. The measured gap this closes: `agentic-research-lab`
had 12 per-file rows in its entry file for 104 modules, `benchmark-core` 6 for
90. Only `brain` (2 modules) and `knowledge-retrieval` (no code) were covered.

Generated files are never hand-edited. A stale MAP.md is worse than no MAP.md,
so `--check` exits 1 when the committed file differs from what this script
produces, and the root gate runs exactly that.

    python scripts/build_project_map.py <project-dir>          # write MAP.md
    python scripts/build_project_map.py --check <project-dir>  # fail if stale

Everything here is parsed, never guessed: roles come from module docstrings,
inputs/outputs from function signatures via `ast`, and "used by" from real
import edges. A module with no docstring gets an empty role cell — the gap is
reported rather than invented.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

# Derived state and vendored trees are not this project's modules. Vendored
# skills are explicitly excluded (D8): a copy of someone else's code is not a
# module of the project that happens to hold it.
EXCLUDED_DIRS = {
    ".git", ".brain", "__pycache__", ".pytest_cache", ".mypy_cache",
    ".ruff_cache", ".ipynb_checkpoints", "skills", "data", "INBOX",
    "results", "plots", "subprojects", "knowledge", "docs", "node_modules",
    ".venv", "venv", ".unlazy",
}

HEADER = """# MAP.md — {name} (generated)

Generated by `scripts/build_project_map.py` from the project's own source.
**Never hand-edit**: run the script. The root gate fails when this file is
stale.

Rows: one per module. `Role` is the module docstring's first line; `Inputs`
and `Outputs` come from the signatures of its public functions; `Used by` is
the set of sibling modules that import it.

"""


def iter_modules(proj: Path) -> list[Path]:
    """Python modules that are this project's own source, sorted for stability."""
    out: list[Path] = []
    for path in proj.rglob("*.py"):
        if EXCLUDED_DIRS & set(path.relative_to(proj).parts):
            continue
        out.append(path)
    return sorted(out, key=lambda p: p.relative_to(proj).as_posix())


def module_facts(path: Path) -> tuple[str, list[str], list[str]]:
    """(role, inputs, outputs) for one module. Empty strings when unknown."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return ("", [], [])

    # A docstring conventionally opens with `modulename.py — `, which repeats
    # the file column and is not a role. Drop the conventional prefix; keep any
    # other first line verbatim.
    role = (ast.get_docstring(tree) or "").strip().splitlines()
    role = re.sub(r"^\S+\.py\s*[—–-]\s*", "", role[0].strip()) if role else ""

    inputs: list[str] = []
    outputs: list[str] = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if node.name.startswith("_"):
            continue
        args = [a.arg for a in node.args.args if a.arg not in ("self", "cls")]
        inputs.append(f"{node.name}({', '.join(args)})")
        # A return *expression* is not an output. What a caller needs to know
        # is the shape of the thing returned: a literal name, a call, a
        # collection, or nothing at all. Raw unparsed expressions produced rows
        # like `return path.read_bytes()[:5] == b'%PDF%'`, which is noise.
        kinds: set[str] = set()
        for r in (n for n in ast.walk(node) if isinstance(n, ast.Return)):
            if r.value is None:
                kinds.add("None")
            elif isinstance(r.value, ast.Name):
                kinds.add(r.value.id)
            elif isinstance(r.value, (ast.Tuple, ast.List, ast.Set)):
                kinds.add("collection")
            elif isinstance(r.value, ast.Dict):
                kinds.add("dict")
            elif isinstance(r.value, ast.Call):
                kinds.add("value")
            else:
                kinds.add("expr")
        if kinds:
            outputs.append(f"{node.name} → {', '.join(sorted(kinds))}")
    return (role, inputs, outputs)


def import_edges(proj: Path, modules: list[Path]) -> dict[str, set[str]]:
    """{module_stem: {modules that import it}} — real imports, not name guesses."""
    stems = {p.stem: p for p in modules}
    edges: dict[str, set[str]] = {p.stem: set() for p in modules}
    for path in modules:
        here = path.stem
        try:
            tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            names: list[str] = []
            if isinstance(node, ast.Import):
                names = [a.name.split(".")[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.module:
                names = [node.module.split(".")[0]]
            for name in names:
                if name in stems and name != here:
                    edges[name].add(here)
    return edges


def _cell(text: str, limit: int = 160) -> str:
    """One table cell: pipes escaped, over-long values truncated with a count.

    A module with 20 public functions would otherwise produce a row wider than
    any screen. Truncating is honest as long as it says how much it dropped.
    """
    if not text:
        return ""
    flat = " ".join(text.split()).replace("|", "\\|")
    if len(flat) <= limit:
        return flat
    return f"{flat[:limit].rstrip()}… (+{len(flat) - limit} chars)"

def render(proj: Path) -> str:
    modules = iter_modules(proj)
    if not modules:
        return (
            f"# MAP.md — {proj.name} (generated)\n\n"
            "No project source to map. This project is documents and evidence.\n"
        )

    edges = import_edges(proj, modules)
    lines = [HEADER.format(name=proj.name)]
    lines.append("| Module | Role | Inputs | Outputs | Used by |")
    lines.append("|---|---|---|---|---|")
    undocumented = 0
    for path in modules:
        role, inputs, outputs = module_facts(path)
        if not role:
            undocumented += 1
        rel = path.relative_to(proj).as_posix()
        used_by = ", ".join(sorted(edges[path.stem])) or "—"
        lines.append(
            f"| `{rel}` | {_cell(role) or '_(no docstring)_'} | "
            f"{_cell('; '.join(inputs)) or '—'} | {_cell('; '.join(outputs)) or '—'} | "
            f"{_cell(used_by) or '—'} |"
        )
    if undocumented:
        lines.append("")
        lines.append(
            f"{undocumented} of {len(modules)} modules have no docstring, so their "
            "role is unknown. That is a real gap, not a rendering failure: add a "
            "docstring to the module and re-run."
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("project", type=Path)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed MAP.md is stale")
    args = ap.parse_args()

    proj = args.project.resolve()
    if not proj.is_dir():
        print(f"not a directory: {proj}", file=sys.stderr)
        return 2

    target = proj / "MAP.md"
    content = render(proj)

    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != content:
            print(
                f"{proj.name}/MAP.md is stale or missing — run "
                f"`python scripts/build_project_map.py {proj.name}`"
            )
            return 1
        return 0

    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {target} ({len(iter_modules(proj))} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
